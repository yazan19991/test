export function t(key: keyof typeof TRANSLATIONS.ar, lang: Language | string = 'ar', params?: Record<string, string | number>): string {
  const safeLang = (lang === 'en' ? 'en' : 'ar') as Language;
  const langDict = TRANSLATIONS[safeLang] || TRANSLATIONS.ar;
  let text = langDict[key] || TRANSLATIONS.ar[key] || String(key);
  if (params) {
    Object.entries(params).forEach(([paramKey, paramVal]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
    });
  }
  return text;
}
